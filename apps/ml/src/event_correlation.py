"""
Sensor ↔ failure association PER EVENT (not only pooled).

Entry point:
    python -m src.event_correlation

The pooled correlation of a sensor with the failure label can be dominated by
one long failure interval (e.g. DV_pressure: r = 0.67 in 2020, ≈ 0 in 2022).
Here every failure is analysed inside its own validation segment (the same
segments the temporal protocol uses): failure rows vs the normal rows of that
segment. Reported per sensor and event:

* r  — point-biserial correlation with the failure label;
* d  — Cohen's d of the failure rows against the segment's normal rows;
* n  — failure / normal rows.

Rows 10 s apart are strongly autocorrelated, so the effective sample size is
far below n: the numbers are DESCRIPTIVE (no p-values). The question they
answer is consistency — does a sensor move the same way in every failure?

Outputs: models/event_correlation.json and docs/event_correlation.md.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

import src.evaluate_cross_dataset as xd
from src.fold_chronology import _label
from src.ingest_metropt import FAILURE_INTERVALS
from src.ingest_metropt2022 import FAILURE_INTERVALS_2022
from src.temporal_validation import events_from_intervals, segment_boundaries

_ML_ROOT: Path = Path(__file__).resolve().parent.parent
OUT_JSON: Path = _ML_ROOT / "models" / "event_correlation.json"
OUT_MD: Path = _ML_ROOT.parent.parent / "docs" / "event_correlation.md"
# Same sensors the served models use (harmonised set).
DROPPED: list[str] = ["Reservoirs", "Oil_level"]


def _assoc(x: np.ndarray, y: np.ndarray) -> dict[str, float | None]:
    pos, neg = x[y == 1], x[y == 0]
    if pos.size < 2 or neg.size < 2 or np.std(x) == 0:
        return {"r": None, "d": None}
    r = float(np.corrcoef(x, y)[0, 1])
    pooled = np.sqrt(
        ((pos.size - 1) * pos.var(ddof=1) + (neg.size - 1) * neg.var(ddof=1))
        / (pos.size + neg.size - 2)
    )
    d = float((pos.mean() - neg.mean()) / pooled) if pooled > 0 else None
    return {"r": r, "d": d}


def analyse() -> dict[str, Any]:
    xd.configure(DROPPED)
    d20, d22 = xd._read(xd.P2020, []), xd._read(xd.P2022, [])
    df = pd.concat([d20, d22], ignore_index=True)
    events = events_from_intervals([*FAILURE_INTERVALS, *FAILURE_INTERVALS_2022])
    segs = segment_boundaries(df["timestamp"], events)
    sensors = list(xd.FEATURES)
    per_event: list[dict[str, Any]] = []
    for ev, (lo, hi) in zip(events, segs):
        m = (df["timestamp"] >= lo) & (df["timestamp"] < hi)
        part = df[m]
        y = part[xd.TARGET_COL].astype(int).to_numpy()
        fid, kind = _label(ev)
        per_event.append(
            {
                "id": fid,
                "type": kind,
                "segment": [str(lo), str(hi)],
                "failure_rows": int(y.sum()),
                "normal_rows": int((1 - y).sum()),
                "sensors": {s: _assoc(part[s].to_numpy(float), y) for s in sensors},
            }
        )
    y_all = df[xd.TARGET_COL].astype(int).to_numpy()
    pooled = {s: _assoc(df[s].to_numpy(float), y_all) for s in sensors}
    summary: dict[str, Any] = {}
    for s in sensors:
        ds = [
            e["sensors"][s]["d"] for e in per_event if e["sensors"][s]["d"] is not None
        ]
        pos = sum(1 for d in ds if d > 0)
        summary[s] = {
            "events": len(ds),
            "positive_d": pos,
            "negative_d": len(ds) - pos,
            "same_sign_share": max(pos, len(ds) - pos) / len(ds) if ds else None,
            "median_abs_d": float(np.median(np.abs(ds))) if ds else None,
            "max_abs_d_event": (
                per_event[
                    int(np.argmax([abs(e["sensors"][s]["d"] or 0) for e in per_event]))
                ]["id"]
                if ds
                else None
            ),
        }
    return {
        "sensors": sensors,
        "pooled": pooled,
        "per_event": per_event,
        "summary": summary,
    }


def _f(v: float | None, fmt: str = "{:+.2f}") -> str:
    return "—" if v is None else fmt.format(v)


def _md(a: dict[str, Any]) -> str:
    ev = a["per_event"]
    lines = [
        "# Sensor ↔ failure association per event",
        "",
        "> Generated by `python -m src.event_correlation` — do not edit by hand.",
        "",
        "Each failure is compared with the normal rows of its own temporal segment (the "
        "segments of the validation protocol). Rows 10 s apart are autocorrelated: the "
        "effective sample size is far below the row counts, so these are descriptive "
        "effect sizes, not significance tests.",
        "",
        "## Cohen's d per event (failure rows − normal rows, in pooled SDs)",
        "",
        "| Sensor | "
        + " | ".join(f"{e['id']} ({e['type']})" for e in ev)
        + " | Pooled r |",
        "|---|" + "---|" * (len(ev) + 1),
    ]
    for s in a["sensors"]:
        cells = [_f(e["sensors"][s]["d"]) for e in ev]
        lines.append(
            f"| {s} | "
            + " | ".join(cells)
            + f" | {_f(a['pooled'][s]['r'], '{:+.3f}')} |"
        )
    lines += [
        "",
        "Rows per event (failure / normal): "
        + "; ".join(
            f"{e['id']} {e['failure_rows']:,} / {e['normal_rows']:,}" for e in ev
        )
        + ".",
        "",
        "## Point-biserial r per event",
        "",
        "| Sensor | " + " | ".join(e["id"] for e in ev) + " |",
        "|---|" + "---|" * len(ev),
    ]
    for s in a["sensors"]:
        lines.append(
            f"| {s} | "
            + " | ".join(_f(e["sensors"][s]["r"], "{:+.3f}") for e in ev)
            + " |"
        )
    lines += [
        "",
        "## Consistency across the 7 failures",
        "",
        "| Sensor | Same sign in | Median abs(d) | Largest effect in |",
        "|---|---|---|---|",
    ]
    for s in a["sensors"]:
        sm = a["summary"][s]
        same = max(sm["positive_d"], sm["negative_d"])
        lines.append(
            f"| {s} | {same}/{sm['events']} | {_f(sm['median_abs_d'], '{:.2f}')} | {sm['max_abs_d_event']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    a = analyse()
    OUT_JSON.write_text(json.dumps(a, indent=1), encoding="utf-8")
    OUT_MD.write_text(_md(a), encoding="utf-8")
    print(f"Wrote {OUT_JSON} and {OUT_MD}")


if __name__ == "__main__":
    main()
