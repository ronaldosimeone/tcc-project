"""
DV_pressure ablation — same folds, same protocol, seed 0.

Entry point:
    python -m src.render_ablation_report

Compares, per model and per tested failure, the full sensor set (main nested
run, ``models/nested/<model>.json``) with two ablations run by
``evaluate_nested --tag``:

* ``no_dv_pressure``   — every sensor except DV_pressure;
* ``dv_pressure_only`` — DV_pressure alone (diagnostic baseline).

Few failures: what matters is consistency across failures (which ones each
variant detects), not small differences in one aggregate.

Output: docs/ablation_dv_pressure.md
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_ML_ROOT: Path = Path(__file__).resolve().parent.parent
NESTED: Path = _ML_ROOT / "models" / "nested"
OUT_MD: Path = _ML_ROOT.parent.parent / "docs" / "ablation_dv_pressure.md"
VARIANTS: dict[str, str] = {
    "full": "",
    "no_dv_pressure": "ablation/no_dv_pressure",
    "dv_pressure_only": "ablation/dv_pressure_only",
}
FOLD_FAILURE: dict[int, str] = {
    1: "F20_2",
    2: "F20_3",
    3: "F20_4",
    4: "F22_1",
    5: "F22_2 (dryer)",
    6: "F22_3 (oil)",
}


def _runs(variant: str, model: str) -> list[dict[str, Any]] | None:
    path = NESTED / VARIANTS[variant] / f"{model}.json"
    if not path.exists():
        return None
    runs = json.loads(path.read_text(encoding="utf-8"))["runs"]
    return sorted((r for r in runs if r["seed"] == 0), key=lambda r: r["fold"])


def render(models: list[str]) -> str:
    lines = [
        "# DV_pressure ablation — same folds, same protocol (seed 0)",
        "",
        "> Generated by `python -m src.render_ablation_report` — do not edit by hand.",
        "",
        "DV_pressure has the largest pooled correlation with the failure label "
        "(r = 0.67 in 2020) but the per-event analysis (`docs/event_correlation.md`) "
        "shows it is driven by three 2020 air leaks. Here the same nested protocol is "
        "re-run without it and with it alone. ✓ = failure detected (persistent alarm in "
        "[start − 6 h, end]).",
        "",
    ]
    for model in models:
        data = {v: _runs(v, model) for v in VARIANTS}
        if data["full"] is None:
            continue
        lines += [
            f"## {model}",
            "",
            "| Variant | "
            + " | ".join(FOLD_FAILURE.values())
            + " | Detected | False-alarm episodes | Mean cost | Mean PR-AUC |",
            "|---|" + "---|" * (len(FOLD_FAILURE) + 4),
        ]
        for v, runs in data.items():
            if runs is None:
                lines.append(
                    f"| {v} | "
                    + " | ".join("…" for _ in FOLD_FAILURE)
                    + " | not run | | | |"
                )
                continue
            by_fold = {r["fold"]: r for r in runs}
            cells = [
                "✓" if by_fold.get(f, {}).get("events", {}).get("detected") else "✗"
                for f in FOLD_FAILURE
            ]
            det = sum(r["events"]["detected"] for r in runs)
            fa = sum(r["events"]["false_alarm_episodes"] for r in runs)
            cost = sum(r["events"]["expected_cost"] for r in runs) / len(runs)
            aps = [r["pr_auc"] for r in runs if r.get("pr_auc") is not None]
            ap = sum(aps) / len(aps) if aps else float("nan")
            lines.append(
                f"| {v} | "
                + " | ".join(cells)
                + f" | {det}/{len(runs)} | {fa} | {cost:.1f} | {ap:.3f} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT_MD.write_text(
        render(["random_forest", "xgboost", "logistic_regression"]), encoding="utf-8"
    )
    print(f"Wrote {OUT_MD}")


if __name__ == "__main__":
    main()
