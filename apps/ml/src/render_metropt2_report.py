"""
Renders docs/metropt2_unseen_failures.md from models/eval_metropt2.json and
models/metropt2_ingest.json — no number in the report is typed by hand.

Entry point:
    python -m src.render_metropt2_report
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_ML_ROOT: Path = Path(__file__).resolve().parent.parent
MODELS: Path = _ML_ROOT / "models"
OUT_MD: Path = _ML_ROOT.parent.parent / "docs" / "metropt2_unseen_failures.md"


def _lead(v: float | None) -> str:
    if v is None:
        return "—"
    hours = v / 60
    return f"{v:+.0f} min" if abs(v) < 120 else f"{hours:+.1f} h"


def _rows(variant: str, block: dict[str, Any]) -> list[str]:
    out = []
    for name, rep in block.items():
        cells = []
        for f in rep["failures"]:
            mark = "✓" if f["detected"] else "✗"
            cells.append(
                f"{mark} | {_lead(f['lead_vs_start_min'])} | {_lead(f['lead_vs_lps_min'])} | "
                f"{_lead(f.get('sustained_lead_vs_lps_min'))}"
            )
        out.append(
            f"| {variant} | {name} | {' | '.join(cells)} | {rep['false_alarms_per_day']:.2f} | "
            f"{rep['pr_auc']:.3f} |"
        )
    return out


def render() -> str:
    ev = json.loads((MODELS / "eval_metropt2.json").read_text(encoding="utf-8"))
    ing = json.loads((MODELS / "metropt2_ingest.json").read_text(encoding="utf-8"))
    apu = ing["same_apu_check"]
    lines = [
        "# MetroPT2 — failures no model has seen (RF-33 / RN-01 / RN-03)",
        "",
        "> Generated by `python -m src.render_metropt2_report` — do not edit by hand.",
        "",
        "## Data",
        "",
        f"* Source: {ing['source']} ({ing['license']}), md5 `{ing['md5']}`.",
        f"* {ing['rows_raw_1hz']:,} rows at 1 Hz → {ing['rows_10s']:,} rows at 10 s "
        f"(same point-sampling as MetroPT 2022), period {ing['period'][0]} → {ing['period'][1]}.",
        f"* Test set: the {ing['rows_after_training_end']:,} rows after "
        f"{ing['training_end']} (end of every training set).",
        "* Failures (maintenance reports):",
    ]
    for f in ing["failures"]:
        lines.append(
            f"  * {f['type']}: {f['start']} → {f['end']} ({f['rows_10s']:,} rows); "
            f"train's own LPS low-pressure alarm at {f['lps_alarm']}."
        )
    lines += [
        "",
        "### Is it the same compressor (APU)?",
        "",
        f"On the {apu['aligned_rows']:,} timestamps both datasets share "
        f"({apu['common_period'][0]} → {apu['common_period'][1]}), TP3 correlation is "
        f"{apu['tp3_correlation']:.3f} (mean |Δ| {apu['tp3_mean_abs_diff_bar']:.2f} bar). "
        f"`Reservoirs` mean {apu['reservoirs_mean']['metropt2']:.2f} vs "
        f"{apu['reservoirs_mean']['metropt_2022']:.2f} bar and `Oil_level` "
        f"{apu['oil_level_mean']['metropt2']:.0f} vs {apu['oil_level_mean']['metropt_2022']:.0f}; "
        f"in MetroPT2 `Reservoirs` ≈ TP3 (r = {apu['reservoirs_tp3_correlation_metropt2']:.4f}). "
        "Two simultaneous, uncorrelated pressure series cannot come from one compressor: "
        "**MetroPT2 is another train's APU**. The test is therefore doubly out-of-sample — "
        "unseen failures on an unseen asset — and no model was re-calibrated for it "
        "(except the physics twin, which by design calibrates on the asset's own healthy weeks).",
        "",
        "## Detection",
        "",
        f"Persistence k = {ev['persistence_k']}, early horizon {ev['early_horizon_h']:.0f} h: a "
        "failure counts as detected when a persistent alarm fires inside "
        "[start − horizon, end]. Lead > 0 = before the reference. *Sustained* = onset of the "
        "first alarm episode lasting ≥ 10 min (gaps ≤ 5 min), declared after an isolated "
        '1-minute blip was found to drive a 2-hour "lead".',
        "",
        "| Variant | Model | Air leak | lead vs start | lead vs LPS | sustained vs LPS | Oil leak | lead vs start | lead vs LPS | sustained vs LPS | False alarms / day | PR-AUC (rows) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    lines += _rows("production (served)", ev["production"])
    lines += _rows("physics twin", ev["physics"])
    if "no_oil" in ev:
        lines += _rows("no oil in training", ev["no_oil"])
    lines += [
        "",
        "## Reading",
        "",
        "* `production` = the exact ONNX artefacts + card thresholds the backend serves "
        "(trained on MetroPT-3 + MetroPT 2022, which contain one oil leak).",
        "* `no oil in training` = same nested recipe, trained only on data before the 2022 "
        "oil leak: models that never saw an oil failure. Comparing it with `production` "
        "isolates what ONE example of a failure type buys on the next occurrence.",
        "* `physics twin` = grey-box residuals calibrated on MetroPT2's own healthy weeks "
        "(no labels, no failure examples).",
        "* Lead vs LPS is the operational comparison: LPS is the alarm the train already "
        "has. A positive value is warning time the platform adds over the status quo.",
        "* Two failures: every rate here is a count over n = 2 and must be read as such.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT_MD.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT_MD}")


if __name__ == "__main__":
    main()
